import {expect,test} from "@playwright/test";
test("Simple flow: JD + CV, generated script, direct meeting, hint and deletion",async({page})=>{
 await page.goto("/signin");
 await page.getByRole("button",{name:/New here/}).click();
 await page.getByLabel("Name").fill("Live Flow Tester");
 await page.getByLabel("Email").fill("live-flow-"+Date.now()+"@example.test");
 await page.getByLabel("Password").fill("correct-horse-battery-staple!");
 await page.getByRole("button",{name:"Create account"}).click();
 await expect(page.getByTestId("live-workspace")).toHaveAttribute("data-hydrated","true");
 await page.getByLabel("Job description").fill("Build resilient data services, respond to database incidents and mentor engineers");
 await page.getByLabel("Or paste/edit CV text").fill("I worked on Node.js services, PostgreSQL reliability and on-call response.");
 await page.getByRole("button",{name:"Generate AI interview scenario"}).click();
 await expect(page.getByText("Focus on production ownership and reliability.")).toBeVisible();
 const plannedAnswer="I would define explicit service boundaries, clear API contracts, reliable retries, and observability before scaling.";
 await expect(page.getByText(plannedAnswer)).toBeHidden();
 await page.getByText("View interview questions & suggested answers").click();
 await page.getByText("Suggested answer",{exact:true}).first().click();
 await expect(page.getByText(plannedAnswer)).toBeVisible();
 // Changing JD invalidates the previous script until the original input is restored.
 const originalJd="Build resilient data services, respond to database incidents and mentor engineers";
 await page.getByLabel("Job description").fill("A changed job description for another role");
 await expect(page.getByTestId("generated-script")).toHaveCount(0);
 await page.getByLabel("Job description").fill(originalJd);
 await expect(page.getByTestId("generated-script")).toBeVisible();
 await page.getByText("Refine script with AI (optional)").click();
 await page.getByLabel("Revision request").fill("Focus more on real database incidents");
 await page.getByRole("button",{name:"Revise with AI"}).click();
 await expect(page.getByText("Revised focus on database incidents.")).toBeVisible();
 // No separate approval or microphone-preflight screens.
 await expect(page.getByRole("navigation",{name:"Interview steps"})).toHaveCount(0);
 await expect(page.getByRole("button",{name:/Start AI meeting/})).toBeDisabled();
 await page.getByRole("checkbox",{name:/I explicitly consent/}).check();
 await page.getByRole("button",{name:/Start AI meeting/}).click();
 await expect(page.getByText("How did you improve database reliability in production?")).toBeVisible();
 const sampleAnswer="I would diagnose slow queries using production traces, review query plans and indexes, then validate safer migrations and alerting against an agreed latency target.";
 await expect(page.getByTestId("suggested-answer")).toHaveCount(0);
 await page.getByRole("button",{name:"Show suggested answer"}).click();
 await expect(page.getByText(sampleAnswer)).toBeVisible();
 await page.getByRole("button",{name:"Hide suggested answer"}).click();
 await expect(page.getByTestId("suggested-answer")).toHaveCount(0);
 await page.getByRole("button",{name:"Show suggested answer"}).click();
 await page.getByRole("button",{name:/Private hint/}).click();
 await expect(page.getByText("Describe the challenge, your actions, measured results, and tradeoffs.")).toBeVisible();
 await page.getByLabel(/Your answer \(speech can be corrected/).fill("We added alerting and slow-query index reviews.");
 await page.getByRole("button",{name:/Commit answer/}).click();
 await expect(page.getByText("We added alerting and slow-query index reviews.")).toBeVisible();
 await expect(page.getByTestId("suggested-answer")).toHaveCount(0);
 await expect(page.getByRole("button",{name:"Show suggested answer"})).toBeVisible();
 await page.getByText("More meeting controls").click();
 await page.getByRole("button",{name:"Pause",exact:true}).click();
 await expect(page.getByText(/PAUSED/).first()).toBeVisible();
 await page.getByRole("button",{name:"Resume",exact:true}).click();
 await page.getByRole("button",{name:"Finish interview"}).click();
 await expect(page.getByText("Recorded answers: 1")).toBeVisible();
 page.on("dialog",dialog=>dialog.accept("DELETE ALL MY INTERVIEW DATA"));
 await page.getByText("Privacy & data").click();
 await page.getByRole("button",{name:"Delete my interview data"}).click();
 await expect(page.getByText("Your interview data has been deleted.")).toBeVisible();
 const sessions=await (await page.request.get("/api/demo/sessions")).json();
 expect(sessions.total).toBe(0);
});
