import {expect,test} from "@playwright/test";

test("Live interview shows planned and current suggested answers",async({page})=>{
 await page.goto("/signin");
 await page.getByRole("button",{name:/New here/}).click();
 await page.getByLabel("Name").fill("Live Flow Tester");
 await page.getByLabel("Email").fill("live-flow-"+Date.now()+"@example.test");
 await page.getByLabel("Password").fill("correct-horse-battery-staple!");
 await page.getByRole("button",{name:"Create account"}).click();
 await expect(page.getByTestId("live-workspace")).toHaveAttribute("data-hydrated","true",{timeout:15_000});

 await page.getByRole("textbox",{name:"Job description",exact:true}).fill("Build resilient data services, respond to database incidents and mentor engineers");
 await page.getByLabel("Or paste/edit CV text").fill("I worked on Node.js services, PostgreSQL reliability and on-call response.");
 await page.getByRole("button",{name:"Create interview scenario"}).click();
 await expect(page.getByRole("button",{name:"Update"})).toBeVisible();
 await page.getByRole("button",{name:"start planning review metting script"}).click();
 await expect(page.getByText("Focus on production ownership and reliability.")).toBeVisible();
 await expect(page.getByText("Standalone",{exact:true}).first()).toBeVisible();
 await expect(page.getByText("Interactive scenario",{exact:true}).first()).toBeVisible();
 const plannedAnswer="I would define explicit service boundaries, clear API contracts, reliable retries, and observability before scaling.";
 await expect(page.getByText(plannedAnswer)).toBeHidden();
 await page.getByText("Suggested answer",{exact:true}).first().click();
 await expect(page.getByText(plannedAnswer)).toBeVisible();

 await page.getByRole("button",{name:/Approve this revision/}).click();
 await page.getByRole("checkbox",{name:/Use typed answers/}).check();
 await page.getByRole("checkbox",{name:/I explicitly consent/}).check();
 await page.getByRole("button",{name:/Start AI meeting/}).click();
 await expect(page.getByText("Explain your service design decisions.",{exact:true}).last()).toBeVisible();
 await expect(page.getByText(/Standalone · One answer/)).toBeVisible();
 const standaloneAnswer="I would define explicit service boundaries, clear API contracts, reliable retries, and observability before scaling.";
 const sampleAnswer="I would diagnose slow queries using production traces, review query plans and indexes, then validate safer migrations and alerting against an agreed latency target.";
 await expect(page.getByTestId("suggested-answer")).toHaveCount(0);
 await page.getByRole("button",{name:"Show suggested answer"}).click();
 await expect(page.getByTestId("suggested-answer").getByText(standaloneAnswer)).toBeVisible();
 await page.getByRole("button",{name:"Hide suggested answer"}).click();
 await expect(page.getByTestId("suggested-answer")).toHaveCount(0);
 await page.getByLabel(/Your answer \(speech can be corrected/).fill("Service boundaries and retry contracts.");
 await page.getByRole("button",{name:/Commit answer/}).click();
 await expect(page.getByText("Walk through a database reliability incident from your project.")).toBeVisible();
 await expect(page.getByText(/Interactive · Production incident deep dive/)).toBeVisible();
 await page.getByRole("button",{name:/Private hint/}).click();
 await expect(page.getByText("Describe the challenge, your actions, measured results, and tradeoffs.")).toBeVisible();
 await page.getByLabel(/Your answer \(speech can be corrected/).fill("We added alerting and slow-query index reviews.");
 await page.getByRole("button",{name:/Commit answer/}).click();
 await expect(page.getByText("How did you improve database reliability in production?")).toBeVisible();
 await expect(page.getByText(/Follow-ups 1\/2/)).toBeVisible();
 await page.getByRole("button",{name:"Show suggested answer"}).click();
 await expect(page.getByTestId("suggested-answer").getByText(sampleAnswer)).toBeVisible();
 await page.getByRole("button",{name:"Finish"}).click();
 await expect(page.getByText("Recorded answers: 2")).toBeVisible();
});
